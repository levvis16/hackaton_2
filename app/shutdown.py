"""Глобальный флаг корректного завершения процесса.

Долгоживущие потоковые ответы (MJPEG) держат HTTP-соединение открытым,
поэтому uvicorn при Ctrl+C ждёт их закрытия и «висит». Флаг позволяет
генератору потока самому завершиться, как только сервер получил сигнал
остановки. Без этого сервис приходится убивать принудительно.
"""
from __future__ import annotations

import threading

_event = threading.Event()


def request_shutdown() -> None:
    """Сообщить всем долгоживущим ответам, что сервис завершается."""
    _event.set()


def is_shutting_down() -> bool:
    """True, если сервис уже завершается."""
    return _event.is_set()


def reset() -> None:
    """Сбросить флаг (вызывается при старте приложения)."""
    _event.clear()